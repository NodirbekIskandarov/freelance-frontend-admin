function derive(prefix: string, count: number): Task[] {
  return Array.from({ length: count }, (_, index) => {
    const source = independentTasks[index % independentTasks.length]!;
    return {
      ...source,
      id: `${prefix}-${index + 1}`,
      order: index + 1,
      code: `DA-101-${prefix}${String(index + 1).padStart(2, '0')}`,
    };
  });
}

